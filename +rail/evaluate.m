function row=evaluate(c,sc,ar,replay,closed,run)
err=replay.estimate-replay.truth;
alertTime=first(replay.t,replay.alert);
if sc.fault=="none"
    responseDelay=NaN;
else
    mask=replay.t>=sc.faultStart & (replay.rejected>0 | replay.diagnostic>0);
    responseTime=first(replay.t,mask); responseDelay=responseTime-sc.faultStart;
end
deadline=NaN; late=NaN; clearance=NaN; collision=false;
if sc.hasObstacle
    distance=rail.stopping_distance(c,sc,c.speed);
    % Latest command for stopping at the obstacle, without the optional reserve.
    % A negative value means braking from t=0 is already insufficient.
    deadline=(c.leaderRear-distance)/c.speed;
    late=double(alertTime>deadline+1e-8);
    clearance=c.leaderRear-closed.truth(end);
    collision=any(closed.truth>=c.leaderRear);
end
row=struct('ScenarioID',sc.id,'Scenario',sc.name,'Architecture',string(ar.name), ...
    'Run',run,'Fusion',ar.fusion,'Controls',ar.controls,'HasObstacle',sc.hasObstacle, ...
    'OpenRMSE_m',sqrt(mean(err.^2)), ...
    'Formal3SigmaCoverage',mean(abs(err)<=3*replay.sigma), ...
    'OpenAlert_s',alertTime,'FaultResponse_s',responseDelay, ...
    'LastSafeCommand_s',deadline,'LateOrMissingAlert',late, ...
    'NoObstacleHazardAlarm',~sc.hasObstacle && any(replay.hazard), ...
    'DiagnosticAlert',any(replay.diagnostic), ...
    'NoObstacleBrake',~sc.hasObstacle && any(isfinite(closed.command)), ...
    'ClosedCollision',collision,'ClosedStopped',closed.speed(end)<1e-8, ...
    'ClosedFinalClearance_m',clearance,'ClosedFinalSpeed_mps',closed.speed(end), ...
    'BrakeCommand_s',min(closed.command), ...
    'ConsistencyRejects',sum(replay.rejected), ...
    'WrongConfidentTrackFraction',mean(replay.wrongConfidentTrack), ...
    'UnknownTrackFraction',mean(~replay.trackKnown), ...
    'MinCovEigenvalue',min([replay.minEig;closed.minEig]), ...
    'ReplaySensorChecksum',sum(replay.sensorChecksum));
end

function t=first(time,mask)
k=find(mask,1); if isempty(k), t=Inf; else, t=time(k); end
end
