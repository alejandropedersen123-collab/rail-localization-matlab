function summary=summarize(T)
rows=struct([]);
ids=unique(T.ScenarioID,'stable'); arches=unique(T.Architecture,'stable');
for j=1:numel(ids)
    for a=1:numel(arches)
        x=T(T.ScenarioID==ids(j) & T.Architecture==arches(a),:);
        r=struct('ScenarioID',ids(j),'Scenario',x.Scenario(1), ...
            'Architecture',arches(a),'Runs',height(x),'HasObstacle',x.HasObstacle(1), ...
            'OpenRMSE_m',mean(x.OpenRMSE_m), ...
            'Formal3SigmaCoverage',mean(x.Formal3SigmaCoverage), ...
            'OpenAlertMedian_s',median(x.OpenAlert_s), ...
            'FaultResponseMedian_s',median(x.FaultResponse_s,'omitnan'), ...
            'LateOrMissingAlertTrials',sum(x.LateOrMissingAlert,'omitnan'), ...
            'NoObstacleHazardAlarmTrials',sum(x.NoObstacleHazardAlarm), ...
            'DiagnosticAlertTrials',sum(x.DiagnosticAlert), ...
            'NoObstacleBrakeTrials',sum(x.NoObstacleBrake), ...
            'ClosedCollisionTrials',sum(x.ClosedCollision), ...
            'ClosedStoppedTrials',sum(x.ClosedStopped), ...
            'ClosedFinalClearanceMean_m',mean(x.ClosedFinalClearance_m,'omitnan'), ...
            'BrakeCommandMedian_s',median(x.BrakeCommand_s), ...
            'ConsistencyRejectMean',mean(x.ConsistencyRejects), ...
            'WrongConfidentTrackFraction',mean(x.WrongConfidentTrackFraction), ...
            'UnknownTrackFraction',mean(x.UnknownTrackFraction));
        if isempty(rows), rows=r; else, rows(end+1)=r; end %#ok<AGROW>
    end
end
summary=struct2table(rows);
end
