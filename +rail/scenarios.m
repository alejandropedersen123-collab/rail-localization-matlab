function s=scenarios()
names=["Nominal approach","GNSS outage","GNSS jump", ...
    "Range outlier","Stale peer message","Motion sensor loss", ...
    "Parallel tracks","Weak brakes","Clear track","Clear track GNSS loss", ...
    "Common position drift","Map displaced","Map alias","Downhill low adhesion", ...
    "Clear track ambiguity","Wheel slip","Clear track phantom peer"];
template=struct('id',0,'name',"",'duration',110,'hasObstacle',true, ...
    'fault',"none",'faultStart',25,'faultEnd',65,'brake',.55,'mu',.3, ...
    'downhill',0,'mapMode',"trusted",'lateralSigma',.6,'mapOffset',0, ...
    'trackSeparation',20,'trueTrack',1);
s=repmat(template,1,numel(names));
faults=["none","gnss_outage","gnss_jump","range_outlier","stale", ...
    "motion_loss","map","weak_brake","none","gnss_outage", ...
    "common_drift","map","map","adhesion","map","wheel_slip","phantom_peer"];
for k=1:numel(s), s(k).id=k; s(k).name=names(k); s(k).fault=faults(k); end
s(8).brake=.12; s(8).duration=300; s(8).faultStart=0;
for k=[9 10 15 17], s(k).hasObstacle=false; s(k).duration=180; end
for k=[7 15]
    s(k).mapMode="measured"; s(k).trackSeparation=4; s(k).lateralSigma=6; s(k).faultStart=0;
end
s(12).mapMode="measured"; s(12).mapOffset=50; s(12).trackSeparation=4; s(12).faultStart=0;
% Wrong map confidently labels real track 1 as track 2: an undetectable alias.
s(13).mapMode="measured"; s(13).mapOffset=-4; s(13).trackSeparation=4; s(13).faultStart=0;
s(14).mu=.035; s(14).downhill=.015; s(14).duration=240; s(14).faultStart=0;
end
